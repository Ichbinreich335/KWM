import { chromium, openApp, VIEWPORTS } from './lib.mjs';
const OUT = new URL('../../vergleich', import.meta.url).pathname;
const browser = await chromium.launch();
const { ctx, page, errs, go } = await openApp(browser, VIEWPORTS.d);
await go('/uebersicht');
const b = page.locator('#vibe-coding1');
await b.getByRole('heading', { name: 'Zu erledigen' }).waitFor({ timeout: 40000 });
await page.waitForTimeout(1500);
const sec = b.locator('section', { has: page.getByRole('heading', { name: 'Zu erledigen' }) });
await sec.screenshot({ path: `${OUT}/softr-23-uebersicht-zu-erledigen-d.png` });
console.log((await sec.innerText()).replace(/\n+/g, ' | ').slice(0, 400));
await go('/erfassen');
const e = page.locator('#vibe-coding1');
await e.getByText('Neues Stück erfassen').waitFor({ timeout: 40000 });
await e.getByRole('button', { name: 'Speichern' }).click();
await page.waitForTimeout(800);
await page.fill('#u-name', 'Probe');
await page.waitForTimeout(300);
console.log('nach Name-Eingabe:', await e.getByText(/^Bitte noch ausfüllen/).innerText());
console.log('errors', errs);
await ctx.close();
await browser.close();
