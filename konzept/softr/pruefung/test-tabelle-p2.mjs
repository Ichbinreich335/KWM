import { chromium, openApp, VIEWPORTS } from './lib.mjs';
const OUT = new URL('../../vergleich', import.meta.url).pathname;
const browser = await chromium.launch();
const { ctx, page, errs, go } = await openApp(browser, VIEWPORTS.d);
await go('/tabelle');
const b = page.locator('#vibe-coding1');
await b.getByText(/von \d+ Einträgen/).waitFor({ timeout: 40000 });
await page.waitForTimeout(1500);
const preis = await b.locator('thead th', { hasText: 'Preis intern' }).boundingBox();
const wrap = await b.locator('div.overflow-auto').first().boundingBox();
console.log('Preis-Spalte sichtbar ohne Scroll:', preis && wrap ? preis.x + preis.width <= wrap.x + wrap.width : 'n/a');
await b.getByRole('button', { name: /^Filter/ }).click();
await b.locator('select[aria-label="Feld"]').first().selectOption('preis');
console.log('Bedingungen Zahl:', await b.locator('select[aria-label="Bedingung"]').first().locator('option').allInnerTexts(), '| Zeilenanfang:', await b.getByText('Wenn', { exact: true }).count());
await b.getByRole('button', { name: 'Ansicht speichern' }).click();
const dlg = page.getByRole('dialog');
await dlg.getByLabel('Name der Ansicht').fill('seladon-stücke verfügbar ab 2026');
console.log('Dublette erkannt:', await dlg.getByText('Diesen Namen gibt es schon').count(), '| Speichern gesperrt:', await dlg.getByRole('button', { name: 'Speichern' }).isDisabled());
await page.screenshot({ path: `${OUT}/softr-44-tabelle-ansicht-dublette-d.png` });
console.log('errors', errs);
await ctx.close();
await browser.close();
