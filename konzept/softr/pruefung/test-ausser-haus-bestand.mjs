import { chromium, openApp, VIEWPORTS } from './lib.mjs';
const OUT = new URL('../../vergleich', import.meta.url).pathname;
const browser = await chromium.launch();
const { ctx, page, errs, go } = await openApp(browser, VIEWPORTS.m);
await go('/bestand');
const b = page.locator('#vibe-coding1');
await b.getByText(/von \d+ Unikaten/).waitFor({ timeout: 40000 });
await page.waitForTimeout(1200);
const tab = b.getByRole('tab', { name: /Außer Haus/ });
await tab.evaluate((el) => el.scrollIntoView({ block: 'center', inline: 'center' }));
await tab.click();
await page.waitForTimeout(600);
console.log('Reiter:', await tab.innerText(), '|', await b.getByText(/von \d+ Unikaten/).innerText());
const card = b.getByRole('button', { name: /Morgenlicht/ }).first();
await card.evaluate((el) => el.scrollIntoView({ block: 'center' }));
await card.click();
const det = page.getByRole('dialog');
await det.waitFor();
await page.waitForTimeout(1200);
console.log('aktiver Status:', await det.getByRole('button', { pressed: true }).first().innerText(), '| Partner-Feld:', await det.locator('#d-galerie').inputValue().then(Boolean), '| Rückgabe:', await det.locator('#d-rueckgabe').inputValue());
await page.screenshot({ path: `${OUT}/softr-22-bestand-ausgestellt-m.png` });
await page.keyboard.press('Escape');
await go('/tabelle');
await page.locator('#vibe-coding1').getByText(/von \d+ Einträgen/).waitFor({ timeout: 40000 });
console.log('Tabelle:', await page.locator('#vibe-coding1').getByText(/von \d+ Einträgen/).innerText());
await go('/erfassen');
await page.locator('#vibe-coding1').getByText('Neues Stück erfassen').waitFor({ timeout: 40000 });
const ag = page.locator('#vibe-coding1').getByRole('radio', { name: 'ausgestellt' });
await ag.evaluate((el) => el.scrollIntoView({ block: 'center' }));
await ag.click();
console.log('Erfassen Partner-Feld bei ausgestellt:', await page.locator('#u-galerie').count());
console.log('errors', errs);
await ctx.close();
await browser.close();
